package snapshot

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"time"
)

// EUVDSource and EPSSSource name the feeds shipward fetches itself.
var (
	EUVDSource = Source{Name: "ENISA EU Vulnerability Database", URL: "https://euvd.enisa.europa.eu", Licence: "source: ENISA", Note: "fetched by shipward from ENISA directly"}
	EPSSSource = Source{Name: "EPSS scores by FIRST.org, generated by Empirical Security", URL: "https://www.first.org/epss", Licence: "attribution requested", Note: "fetched by shipward from the source directly"}
)

// Live fetches ENISA's exploited list and FIRST's EPSS scores from the sources, at most once per MaxAge, and keeps
// them in CacheDir. Their reuse terms do not clearly allow passing them on, so the snapshot does not carry them.
type Live struct {
	Fetcher  *Fetcher
	CacheDir string
	EUVDURL  string
	EPSSURL  string
	MaxAge   time.Duration
	Now      func() time.Time
	// Offline uses only cached copies, of any age, and makes no request.
	Offline bool
}

// LiveData is what Live returns. Warnings say which feed is old or missing.
type LiveData struct {
	EUVD     map[string]EUVD
	EPSS     map[string]EPSS
	EPSSDate string
	// EUVDFetched and EPSSFetched are when shipward fetched the copy it used. EUVD or EPSS is nil when that feed was
	// not used.
	EUVDFetched, EPSSFetched time.Time
	Warnings                 []string
}

// Load returns the EUVD entries and the EPSS scores of the given CVEs.
func (l *Live) Load(ctx context.Context, cves map[string]bool) LiveData {
	var d LiveData
	data, fetched, warn := l.cached(ctx, "euvd.json", func() ([]byte, error) {
		m, err := l.Fetcher.EUVD(ctx, l.EUVDURL)
		if err != nil {
			return nil, err
		}
		return json.Marshal(m)
	})
	d.addWarning(warn)
	if data != nil {
		if err := json.Unmarshal(data, &d.EUVD); err != nil {
			d.EUVD = nil
			d.addWarning("euvd.json: " + err.Error())
		} else {
			d.EUVDFetched = fetched
		}
	}

	data, fetched, warn = l.cached(ctx, "epss.csv.gz", func() ([]byte, error) {
		var buf bytes.Buffer
		err := l.Fetcher.download(ctx, l.EPSSURL, &buf)
		return buf.Bytes(), err
	})
	d.addWarning(warn)
	if data != nil {
		m, date, err := ParseEPSS(bytes.NewReader(data), func(c string) bool { return cves[c] })
		if err != nil {
			d.addWarning("EPSS: " + err.Error())
		} else {
			d.EPSS, d.EPSSDate, d.EPSSFetched = m, date, fetched
		}
	}
	return d
}

func (d *LiveData) addWarning(w string) {
	if w != "" {
		d.Warnings = append(d.Warnings, w)
	}
}

// cached returns a feed file and when it was fetched: the cached copy when it is young enough, else a fresh one. If
// fetching fails, an older copy is still used, with a warning.
func (l *Live) cached(ctx context.Context, name string, fetch func() ([]byte, error)) ([]byte, time.Time, string) {
	p := filepath.Join(l.CacheDir, name)
	old, readErr := os.ReadFile(p)
	var oldTime time.Time
	if readErr == nil {
		if info, err := os.Stat(p); err == nil {
			oldTime = info.ModTime()
		}
	}
	if l.Offline {
		if readErr == nil {
			return old, oldTime, ""
		}
		return nil, time.Time{}, name + ": not cached (offline)"
	}
	if readErr == nil && !oldTime.IsZero() && l.Now().Sub(oldTime) < l.MaxAge {
		return old, oldTime, ""
	}
	fresh, err := fetch()
	if err == nil && len(fresh) > 0 {
		if os.MkdirAll(l.CacheDir, 0o755) == nil {
			_ = writeAtomic(p, fresh)
		}
		return fresh, l.Now(), ""
	}
	if err == nil {
		err = errors.New("empty response")
	}
	if readErr == nil {
		return old, oldTime, fmt.Sprintf("%s: could not fetch a new copy (%v); using an older one", name, err)
	}
	return nil, time.Time{}, fmt.Sprintf("%s: not available (%v)", name, err)
}
